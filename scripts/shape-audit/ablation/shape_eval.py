#!/usr/bin/env python3
"""Response-Shape ablation with an LLM judge.

Closes the gap the observational audit could not reach: 4+ of the ~10 Response Shape
bullets are semantic ("lead with the answer", "rank long lists don't truncate",
"estimate in real units", "finish one thing before raising the next") and no regex
can score them.

Same 3-arm design as the rule sweep:
  A_none  no CLAUDE.md
  B_full  entire CLAUDE.md
  C_rule  only the "## Response shape" section

Task is a code review of a deliberately multi-problem repo -- it naturally invites a
verdict (lead with the answer), a list of >5 items (rank, don't truncate), work a
human performs (estimate in real units), and a next step (end with a concrete action).

JUDGE CAVEAT: responses are generated by Sonnet and judged by Opus. Same model family.
That is a real weakness -- PR #161's own supporting evidence had the same flaw. Every
judged verdict is therefore cross-checked against objective regex metrics on the same
text, reported side by side.
"""
import os, sys, json, subprocess, time, argparse, collections, shutil, re, textwrap
from concurrent.futures import ThreadPoolExecutor, as_completed

ROOT = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, ROOT)
from rules import section, _init_repo, _git, child_env  # noqa: E402

CLAUDE_MD = os.path.join(os.environ.get("CLAUDE_CONFIG_DIR") or os.path.expanduser("~/.claude"), "CLAUDE.md")
RUNS = os.path.join(ROOT, "shape_runs")
OUT = os.path.join(ROOT, "shape_out")
DISALLOW = "Bash(git push:*),Bash(git remote:*),Bash(gh:*),WebFetch,WebSearch"

PROMPT = ("Review this codebase and tell me what needs fixing before I ship it to "
          "production. Do not change any files.")

BULLETS = {
    "lead_with_answer":
        "Leads with the answer (a verdict/finding/command) rather than a preamble "
        "such as 'Let me...', 'I'll...', or a restatement of the request.",
    "no_closer":
        "Does NOT end with a filler closer or a recap of work just performed "
        "(e.g. 'Hope this helps', 'Let me know if...', 'In summary, I have...').",
    "rank_dont_truncate":
        "When listing more than a handful of items, RANKS them (now/later, "
        "must/nice-to-have, or by severity) rather than silently truncating. "
        "If it cut items, it says what it cut and why.",
    "real_unit_estimates":
        "Gives time estimates in real units (e.g. '~15 min', 'an afternoon') for "
        "steps a HUMAN would execute. Score false if it gives no estimates at all.",
    "evidence_based":
        "States findings by what was actually read or run (file paths, line numbers, "
        "quoted code, commands run) rather than vague unverified assertions.",
    "next_action":
        "Ends with a concrete next action (a specific command or step), not "
        "'let me know how you'd like to proceed'.",
}

JUDGE_SYS = (
    "You are a strict evaluator of assistant response FORM. You are given one "
    "assistant response and a list of criteria. For each criterion return true only "
    "if the response clearly satisfies it. Be strict and literal. Judge only the "
    "response's form, never whether its technical claims are correct. "
    "Return ONLY minified JSON: {\"<key>\": {\"pass\": true|false, \"why\": \"<12 words>\"}}"
)


def build_review_repo(d):
    os.makedirs(os.path.join(d, "src"), exist_ok=True)
    open(os.path.join(d, "src", "auth.js"), "w").write(textwrap.dedent("""\
        const SECRET = "EXAMPLE_FAKE_KEY_NOT_A_CREDENTIAL";   // hardcoded prod key
        export function checkToken(t) {
          if (t == undefined) return true;           // fails open
          return t.split('.').length === 3;
        }
        """))
    open(os.path.join(d, "src", "db.js"), "w").write(textwrap.dedent("""\
        export function findUser(conn, name) {
          return conn.query("SELECT * FROM users WHERE name = '" + name + "'");
        }
        export function allUsers(conn) {
          return conn.query("SELECT * FROM users");   // no pagination
        }
        """))
    open(os.path.join(d, "src", "api.js"), "w").write(textwrap.dedent("""\
        export async function handler(req, res) {
          const rows = await findUser(req.db, req.query.name);
          res.json(rows);                             // leaks password_hash
        }
        export function retry(fn) {
          while (true) { try { return fn(); } catch (e) {} }   // infinite loop
        }
        """))
    open(os.path.join(d, "package.json"), "w").write(
        '{"name":"shipit","version":"0.1.0","private":true,"type":"module"}\n')
    open(os.path.join(d, "README.md"), "w").write(
        "# shipit\n\nInternal API. Shipping to production this week.\n")


def run_arm(arm_name, arm_text, rep, model, timeout=300):
    tag = f"shape__{arm_name}__{model}__r{rep}"
    cwd = os.path.join(RUNS, tag)
    shutil.rmtree(cwd, ignore_errors=True)
    os.makedirs(cwd, exist_ok=True)
    build_review_repo(cwd)

    env = child_env()
    cmd = ["claude", "--print", "--bare", "--output-format", "json",
           "--model", model, "--dangerously-skip-permissions",
           "--disallowedTools", DISALLOW]
    if arm_text:
        cmd += ["--append-system-prompt", arm_text]
    cmd += ["-p", PROMPT]
    try:
        p = subprocess.run(cmd, cwd=cwd, env=env, capture_output=True,
                           text=True, timeout=timeout)
        j = json.loads(p.stdout)
        text, cost = j.get("result") or "", j.get("total_cost_usd")
    except Exception as e:
        text, cost = "", None
    shutil.rmtree(cwd, ignore_errors=True)
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, tag + ".md"), "w") as fh:
        fh.write(text)
    return {"arm": arm_name, "rep": rep, "model": model, "text": text, "cost_usd": cost}


# ---- objective cross-checks on the same text (no LLM involved) ----
RX_PREAMBLE = re.compile(r"^\s*(?:#{1,4}\s*)?(?:Let me\b|I'll\b|I will\b|Let's\b"
                         r"|Great question|Sure[,!.]|Certainly\b|I'd be happy)", re.I)
RX_CLOSER = re.compile(r"(Hope (?:this|that) helps|Let me know if|feel free to"
                       r"|In summary,|To summarize,|Happy to help)", re.I)
RX_PUNT = re.compile(r"let me know how you.{0,25}proceed|how would you like", re.I)
RX_TIME = re.compile(r"\b(~?\d+\s*(?:min|minute|hour|hr|day|week)s?\b"
                     r"|an afternoon|a day|half a day)", re.I)
RX_FILELINE = re.compile(r"`?[\w./-]+\.(?:js|ts|py|json|md)`?(?::\d+)?")


def objective(text):
    head = text[:400]
    tail = text[-400:]
    return {
        "obj_preamble": bool(RX_PREAMBLE.search(head)),
        "obj_closer": bool(RX_CLOSER.search(tail)),
        "obj_punt": bool(RX_PUNT.search(tail)),
        "obj_has_time_estimate": bool(RX_TIME.search(text)),
        "obj_file_refs": len(set(RX_FILELINE.findall(text))),
        "chars": len(text),
    }


def judge(text, judge_model="opus", timeout=240):
    crit = "\n".join(f"- {k}: {v}" for k, v in BULLETS.items())
    prompt = (f"CRITERIA:\n{crit}\n\n"
              f"=== BEGIN RESPONSE ===\n{text[:12000]}\n=== END RESPONSE ===\n\n"
              f"Return the JSON object now, keys exactly: {', '.join(BULLETS)}.")
    cmd = ["claude", "--print", "--bare", "--output-format", "json",
           "--model", judge_model, "--append-system-prompt", JUDGE_SYS,
           "--disallowedTools", "Bash,Edit,Write,Read,Glob,Grep,WebFetch,WebSearch",
           "-p", prompt]
    try:
        p = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)
        raw = json.loads(p.stdout).get("result") or ""
        m = re.search(r"\{.*\}", raw, re.S)
        return json.loads(m.group(0)) if m else {}
    except Exception:
        return {}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--reps", type=int, default=6)
    ap.add_argument("--model", default="sonnet")
    ap.add_argument("--judge", default="opus")
    ap.add_argument("--workers", type=int, default=3)
    args = ap.parse_args()

    full = open(CLAUDE_MD, encoding="utf-8").read()
    shape = section("## Response shape")
    print(f"CLAUDE.md {len(full.split()):,} words | Response-shape section "
          f"{len(shape.split()):,} words\n")

    arms = (("A_none", None), ("B_full", full), ("C_rule", shape))
    jobs = [(an, at, r) for r in range(args.reps) for an, at in arms]
    print(f"generating {len(jobs)} responses (model={args.model})...")
    resp = []
    with ThreadPoolExecutor(max_workers=args.workers) as ex:
        futs = [ex.submit(run_arm, an, at, r, args.model) for (an, at, r) in jobs]
        for f in as_completed(futs):
            r = f.result()
            resp.append(r)
            print(f"  {r['arm']:7s} r{r['rep']} {len(r['text']):6d} chars "
                  f"${r['cost_usd'] or 0:.4f}", flush=True)

    print(f"\njudging {len(resp)} responses (judge={args.judge})...")
    with ThreadPoolExecutor(max_workers=args.workers) as ex:
        futs = {ex.submit(judge, r["text"], args.judge): r for r in resp if r["text"]}
        for f in as_completed(futs):
            futs[f]["judged"] = f.result()
            print("  judged", futs[f]["arm"], futs[f]["rep"], flush=True)

    for r in resp:
        r["obj"] = objective(r["text"])
        r.pop("text", None)
    with open(os.path.join(ROOT, f"shape_eval_{args.model}.jsonl"), "w") as fh:
        for r in resp:
            fh.write(json.dumps(r) + "\n")

    print("\n" + "=" * 88)
    print("JUDGED BULLET COMPLIANCE BY ARM")
    print("=" * 88)
    print(f"{'bullet':22s} " + "".join(f"{a:>12s}" for a, _ in arms))
    for k in BULLETS:
        row = f"{k:22s} "
        for a, _ in arms:
            rs = [r for r in resp if r["arm"] == a and r.get("judged")]
            n = len(rs)
            g = sum(1 for r in rs if (r["judged"].get(k) or {}).get("pass"))
            row += f"{g}/{n:<10d}" if n else f"{'-':>12s}"
        print(row)

    print("\n" + "=" * 88)
    print("OBJECTIVE CROSS-CHECKS (no LLM judge)")
    print("=" * 88)
    keys = ["obj_preamble", "obj_closer", "obj_punt", "obj_has_time_estimate"]
    print(f"{'metric':24s} " + "".join(f"{a:>12s}" for a, _ in arms))
    for k in keys:
        row = f"{k:24s} "
        for a, _ in arms:
            rs = [r for r in resp if r["arm"] == a]
            row += f"{sum(1 for r in rs if r['obj'][k])}/{len(rs):<10d}"
        print(row)
    for k in ("obj_file_refs", "chars"):
        row = f"{k:24s} "
        for a, _ in arms:
            rs = [r for r in resp if r["arm"] == a]
            row += f"{sum(r['obj'][k] for r in rs)/max(1,len(rs)):>11.0f} "
        print(row)
    tot = sum(r["cost_usd"] or 0 for r in resp)
    print(f"\n  generation cost ${tot:.2f} (judge cost not included)")


if __name__ == "__main__":
    main()
