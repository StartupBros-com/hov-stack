#!/usr/bin/env node
// Builds scripts/vendor/: one CommonJS file per runtime package, bundled with esbuild-wasm
// from the versions pnpm-lock.yaml pins, plus NOTICE carrying the license of everything
// bundled. A plugin install copies this directory and runs nothing, so there is never a
// node_modules beside the CLI; the CLI loads these files instead (#364).
//
//   pnpm install --frozen-lockfile && node tools/vendor.mjs     rebuild after a lockfile change
//   node tools/vendor.mjs --check                                exit 1 when a committed file differs
//
// The output is the same on every machine: esbuild-wasm is pinned, and pnpm's store paths
// (node_modules/.pnpm/<pkg>@<version>/node_modules/) are rewritten to node_modules/, so the
// bytes depend on the lockfile and not on the installer's folder layout.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const SKILL_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = path.join(SKILL_DIR, 'scripts', 'vendor');
const OUT_REL = 'scripts/vendor';
const PACKAGES = ['fflate', 'jpeg-js', 'pdf-lib', 'pngjs'];
const LICENSE_FILE = /^(licen[cs]e|copying)(\.(md|txt))?$/i;
const PNPM_STORE = /node_modules\/\.pnpm\/[^/\s"'`]+\/node_modules\//g;

const check = process.argv.includes('--check');
const unknown = process.argv.slice(2).filter(a => a !== '--check');
if (unknown.length) { console.error(`vendor: unknown argument ${unknown.join(' ')} (usage: node tools/vendor.mjs [--check])`); process.exit(2); }

const require = createRequire(path.join(SKILL_DIR, 'package.json'));
let esbuild;
try { esbuild = require('esbuild-wasm'); }
catch { console.error('vendor: esbuild-wasm is not installed; run `pnpm install --frozen-lockfile` in this skill first'); process.exit(2); }

// The package a bundled input file belongs to: everything after its last node_modules/.
function packageRoot(input) {
  const at = input.lastIndexOf('node_modules/');
  if (at < 0) return null;
  const rest = input.slice(at + 'node_modules/'.length).split('/');
  const name = rest[0].startsWith('@') ? `${rest[0]}/${rest[1]}` : rest[0];
  return path.join(SKILL_DIR, input.slice(0, at), 'node_modules', name);
}

function readPackage(root) {
  const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
  const file = fs.readdirSync(root).filter(f => LICENSE_FILE.test(f)).sort()[0];
  if (!file) throw new Error(`${pkg.name}@${pkg.version} ships no license file; add its notice by hand before bundling it`);
  const text = fs.readFileSync(path.join(root, file), 'utf8').replace(/\r\n?/g, '\n').trim();
  return { name: pkg.name, version: pkg.version, license: pkg.license || 'see text', text };
}

const files = new Map();   // file name in scripts/vendor -> contents
const bundled = new Map(); // "name@version" -> { name, version, license, text, in: Set }
for (const name of PACKAGES) {
  const { version } = JSON.parse(fs.readFileSync(path.join(packageRoot(`node_modules/${name}/x`), 'package.json'), 'utf8'));
  const banner = [
    `// sign-it vendored copy of ${name}@${version} and its dependencies, generated by tools/vendor.mjs`,
    `// from pnpm-lock.yaml. Do not edit: change the lockfile and run \`node tools/vendor.mjs\`.`,
    `// Licenses: ${OUT_REL}/NOTICE.`,
  ].join('\n');
  const result = await esbuild.build({
    stdin: { contents: `module.exports = require(${JSON.stringify(name)});\n`, resolveDir: SKILL_DIR, sourcefile: `${name}.cjs`, loader: 'js' },
    absWorkingDir: SKILL_DIR,
    bundle: true, platform: 'node', format: 'cjs', target: 'node18',
    legalComments: 'eof', banner: { js: banner },
    metafile: true, write: false, logLevel: 'warning',
  });
  files.set(`${name}.cjs`, result.outputFiles[0].text.replace(PNPM_STORE, 'node_modules/'));
  for (const input of Object.keys(result.metafile.inputs)) {
    const root = packageRoot(input);
    if (!root) continue;
    const info = readPackage(root);
    const key = `${info.name}@${info.version}`;
    if (!bundled.has(key)) bundled.set(key, { ...info, in: new Set() });
    bundled.get(key).in.add(`${name}.cjs`);
  }
}
if (typeof esbuild.stop === 'function') await esbuild.stop();

const rule = '-'.repeat(72);
const notice = [
  'Third-party code in this directory',
  '',
  'Each .cjs file here bundles one of sign-it\'s runtime packages with the packages it',
  'depends on, built by tools/vendor.mjs from the versions pnpm-lock.yaml pins. Each',
  'bundled package\'s license follows.',
  '',
  ...[...bundled.values()].sort((a, b) => a.name.localeCompare(b.name)).flatMap(p => [
    rule, `${p.name} ${p.version} (${p.license}), in ${[...p.in].sort().join(', ')}`, rule, '', p.text, '',
  ]),
].join('\n');
files.set('NOTICE', notice);

// Where a committed file first departs from the rebuild, so a mismatch seen only on another
// machine (a different pnpm layout, say) can be read from its log.
function firstDifference(f, rebuilt) {
  const file = path.join(OUT_DIR, f);
  if (!fs.existsSync(file)) return `  ${f}: not committed`;
  const a = fs.readFileSync(file, 'utf8').split('\n'), b = rebuilt.split('\n');
  let i = 0; while (i < a.length && i < b.length && a[i] === b[i]) i++;
  const clip = s => (s === undefined ? '(end of file)' : JSON.stringify(s.length > 160 ? `${s.slice(0, 160)}...` : s));
  return `  ${f}: first difference at line ${i + 1} of ${a.length} committed, ${b.length} rebuilt\n    committed: ${clip(a[i])}\n    rebuilt:   ${clip(b[i])}`;
}

const present = fs.existsSync(OUT_DIR) ? fs.readdirSync(OUT_DIR).filter(f => f.endsWith('.cjs') || f === 'NOTICE') : [];
if (check) {
  const stale = [...files].filter(([f, text]) => !fs.existsSync(path.join(OUT_DIR, f)) || fs.readFileSync(path.join(OUT_DIR, f), 'utf8') !== text).map(([f]) => f);
  const extra = present.filter(f => !files.has(f));
  if (stale.length || extra.length) {
    if (stale.length) console.error(`vendor: ${OUT_REL} differs from a rebuild from pnpm-lock.yaml: ${stale.join(', ')}`);
    for (const f of stale) console.error(firstDifference(f, files.get(f)));
    if (extra.length) console.error(`vendor: ${OUT_REL} holds files no package produces: ${extra.join(', ')}`);
    console.error('vendor: run `pnpm install --frozen-lockfile && node tools/vendor.mjs` in this skill and commit the result');
    process.exit(1);
  }
  console.log(`vendor: ${OUT_REL} matches a rebuild from pnpm-lock.yaml (${[...files.keys()].join(', ')})`);
} else {
  fs.mkdirSync(OUT_DIR, { recursive: true });
  for (const f of present) if (!files.has(f)) fs.rmSync(path.join(OUT_DIR, f));
  for (const [f, text] of files) fs.writeFileSync(path.join(OUT_DIR, f), text);
  console.log(`vendor: wrote ${OUT_REL}/${[...files.keys()].join(`, ${OUT_REL}/`)}`);
  for (const p of [...bundled.values()].sort((a, b) => a.name.localeCompare(b.name))) console.log(`  ${p.name}@${p.version} (${p.license}) in ${[...p.in].sort().join(', ')}`);
}
