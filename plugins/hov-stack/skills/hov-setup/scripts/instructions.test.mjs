const DATA_NAMES = [
  "gsc",
  "ga4",
  "discord-cli",
  "resend-cli",
  "stripe-api",
  "posthog-api",
  "supabase-api",
  "fal-api",
  "dfs",
  "exa-cli",
  "firecrawl-cli",
  "vastai",
  "vast-ssh",
];
// The config dir's bin/<name> (what ./setup links), and a directory of links to it.
function dataCommands(dir, cfg, names = DATA_NAMES, linked = names) {
  const links = join(dir, "local-bin");
  mkdirSync(join(cfg, "bin"), { recursive: true });
  mkdirSync(links, { recursive: true });
  for (const name of names) {
    writeFileSync(join(cfg, "bin", name), "#!/bin/sh\nexit 99\n");
    chmodSync(join(cfg, "bin", name), 0o755);
  }
  for (const name of linked) symlinkSync(join(cfg, "bin", name), join(links, name));
  return links;
}
test("data commands PATH runs from the config dir get one line, in DATA_CLIS order, with their notes", () =>
  withFake(({ dir, cfg, target, cli, env, tool }) => {
    tool();
    env.PATH = `${dir}:${dataCommands(dir, cfg)}`;
    const r = cli("--json");
    assert.equal(r.status, 0, r.stderr);
    const out = JSON.parse(r.stdout);
    assert.deepEqual(out.tools, ["gh", "data-commands"]);
    assert.deepEqual(out.leftOut, []);
    const text = readFileSync(target, "utf8");
    const line = source("data-commands").replace(
      "{commands}",
      "`gsc`, `ga4`, `discord-cli`, `resend-cli`, `stripe-api`, `posthog-api`, `supabase-api`, `fal-api` (live money), `dfs`, `exa-cli`, `firecrawl-cli`, `vastai` (live money), `vast-ssh`",
    );
    assert.ok(text.endsWith(`${source("gh")}\n${line}\n`), text);
    assert.ok(!text.includes("{commands}"));
    assert.equal(cli().stdout, "ok: rules/hov-stack-tools.md is current; mentions gh, data-commands\n");
  }));
test("a data command the config dir lacks is silent; one PATH runs from elsewhere is left out", () =>
  withFake(({ dir, cfg, target, cli, env }) => {
    const links = dataCommands(dir, cfg, ["gsc", "ga4", "vastai"], ["gsc", "ga4"]);
    const own = join(dir, "own");
    mkdirSync(own);
    writeFileSync(join(own, "vastai"), "#!/bin/sh\nexit 99\n");
    chmodSync(join(own, "vastai"), 0o755);
    symlinkSync(join(cfg, "bin", "vastai"), join(links, "vastai"));
    env.PATH = `${dir}:${own}:${links}`;
    const out = JSON.parse(cli("--json").stdout);
    assert.deepEqual(out.tools, ["data-commands"]);
    assert.deepEqual(out.leftOut, [
      { name: "data-commands", why: "vastai: what PATH runs first is not hov-stack's" },
    ]);
    assert.match(out.reason, /left out: data-commands \(vastai: what PATH runs first is not hov-stack's\)$/);
    const text = readFileSync(target, "utf8");
    assert.ok(text.includes(": `gsc`, `ga4`. Their sends"), text);
    for (const name of ["vastai", "discord-cli", "fal-api"]) assert.ok(!text.includes(`\`${name}\``), name);
  }));
test("data commands off PATH or unlinked are left out under one reason, naming the rest only when some are", () =>
  withFake(({ dir, cfg, target, cli, env }) => {
    const links = dataCommands(dir, cfg);
    env.HOV_SETUP_EXTRA_BIN_DIRS = links;
    let out = JSON.parse(cli("--json").stdout);
    assert.deepEqual(out.tools, []);
    assert.deepEqual(out.leftOut, [{ name: "data-commands", why: `${links} is not on PATH` }]);
    assert.equal(existsSync(target), false);
    env.HOV_SETUP_EXTRA_BIN_DIRS = "";
    out = JSON.parse(cli("--json").stdout);
    assert.deepEqual(out.leftOut, [{ name: "data-commands", why: "not on PATH: run ./setup" }]);
    for (const name of DATA_NAMES.slice(1)) rmSync(join(links, name));
    env.PATH = `${dir}:${links}`;
    out = JSON.parse(cli("--json").stdout);
    assert.deepEqual(out.tools, ["data-commands"]);
    assert.deepEqual(out.leftOut, [
      { name: "data-commands", why: `${DATA_NAMES.slice(1).join(", ")}: not on PATH: run ./setup` },
    ]);
    assert.ok(readFileSync(target, "utf8").includes(": `gsc`. Their sends"));
  }));
