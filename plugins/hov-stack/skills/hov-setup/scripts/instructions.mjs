#!/usr/bin/env node
/*
  Writes Claude's tool instructions: <config-dir>/rules/hov-stack-tools.md, holding
  ../instructions/<offer>.md for each installed offer that has one, in offers.json order,
  then ../instructions/data-commands.md naming the bundled data commands on PATH.
  Every line names a command Claude will run, so a tool counts only when its program is on
  PATH, codex only when the codex program is on PATH as well, and a data command only when
  PATH runs the config dir's own bin/<name> (the link ./setup makes), never a copy of the
  user's own. The file is written
  atomically and removed when no offer contributes. Nothing is written through a rules/ that
  is a symlink (its rules files are read for the lines instead), over a symlink, or over a
  file without this file's header. A failed detection changes nothing.

  Usage: node instructions.mjs [--config-dir DIR] [--check] [--json]
  Config dir: $CLAUDE_CONFIG_DIR, else ~/.claude. --check never writes.
  Prints "<state>: <reason>", or with --json {code, state, path, reason, tools, leftOut}.
  Exit: 0 ok; 3 missing or stale (in --check, or lines a symlinked rules/ lacks);
  1 blocked; 2 bad usage.
*/
import {
  lstatSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  realpathSync,
  renameSync,
  statSync,
  unlinkSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { randomUUID } from "node:crypto";
import { configDir } from "./autoupdate.mjs";
import { detect, findBin, searchDirs } from "./detect.mjs";

const HEADER =
  "<!-- Generated by hov-stack: ./setup, ./setup --update and /hov-setup regenerate this file. Edits are lost. Lines come from plugins/hov-stack/skills/hov-setup/instructions/<offer>.md. -->\n";
const SOURCES = fileURLToPath(new URL("../instructions/", import.meta.url));
const FILE = "rules/hov-stack-tools.md";
// Offers whose lines also need a program that installing the offer does not install.
const NEEDS = { codex: "codex" };
// The data commands ./setup links into ~/.local/bin, in lib/manifest.sh's DATA_CLIS order
// (instructions.test.mjs holds the two equal), with the note a command carries in the line.
export const DATA_COMMANDS = [
  ["gsc"],
  ["ga4"],
  ["discord-cli"],
  ["resend-cli"],
  ["stripe-api"],
  ["posthog-api"],
  ["supabase-api"],
  ["fal-api", "live money"],
  ["dfs"],
  ["exa-cli"],
  ["firecrawl-cli"],
  ["vastai", "live money"],
  ["vast-ssh"],
];
const DATA = "data-commands";

function stat(path) {
  try {
    return lstatSync(path);
  } catch (e) {
    if (e.code === "ENOENT") return null;
    throw e;
  }
}

// Every trimmed line of the .md files under dir, a few levels down: what Claude Code loads
// from a rules/ that ./setup does not write into.
function ruleLines(dir, depth = 0, out = new Set()) {
  if (depth > 4) return out;
  let entries;
  try {
    entries = readdirSync(dir);
  } catch {
    return out;
  }
  for (const name of entries) {
    const p = join(dir, name);
    let s;
    try {
      s = statSync(p);
    } catch {
      continue;
    }
    if (s.isDirectory()) ruleLines(p, depth + 1, out);
    else if (s.isFile() && name.endsWith(".md"))
      for (const l of readFileSync(p, "utf8").split(/\r?\n/)) out.add(l.trim());
  }
  return out;
}

function realOrNull(p) {
  try {
    return realpathSync(p);
  } catch {
    return null;
  }
}

// The data-commands block, or null when no command is listed; what is left out is pushed
// onto leftOut as one entry per reason. A command the config dir's bin/ lacks is silent:
// that is a plugin-only install, not a missing link.
function dataBlock(cfg, search, leftOut) {
  const listed = [],
    absent = [],
    notOurs = [],
    offPath = new Map();
  let held = 0;
  for (const [name, note] of DATA_COMMANDS) {
    const ours = realOrNull(join(cfg, "bin", name));
    if (!ours) continue;
    held++;
    const found = findBin(name, search);
    if (!found.path) absent.push(name);
    else if (realOrNull(found.path) !== ours) notOurs.push(name);
    else if (!found.onPath) {
      const dir = dirname(found.path);
      offPath.set(dir, [...(offPath.get(dir) || []), name]);
    } else listed.push(note ? `\`${name}\` (${note})` : `\`${name}\``);
  }
  // A reason every held command shares names none of them: ./setup links all or none.
  const who = (names) => (names.length === held ? "" : `${names.join(", ")}: `);
  if (absent.length) leftOut.push({ name: DATA, why: `${who(absent)}not on PATH: run ./setup` });
  for (const [dir, names] of offPath)
    leftOut.push({ name: DATA, why: `${who(names)}${dir} is not on PATH` });
  if (notOurs.length)
    leftOut.push({
      name: DATA,
      why: `${who(notOurs)}what PATH runs first is not hov-stack's`,
    });
  if (!listed.length) return null;
  const template = readFileSync(join(SOURCES, `${DATA}.md`), "utf8").trim();
  return { name: DATA, text: template.replace("{commands}", listed.join(", ")) };
}

// The blocks this config dir should get, and the installed offers left out, with why.
function wanted(report, cfg) {
  const blocks = [],
    leftOut = [],
    search = searchDirs();
  for (const offer of report.plugins) {
    if (offer.state !== "installed") continue;
    let text;
    try {
      text = readFileSync(join(SOURCES, `${offer.name}.md`), "utf8").trim();
    } catch (e) {
      if (e.code === "ENOENT") continue;
      throw e;
    }
    if (!text) continue;
    if (offer.onPath === false) {
      leftOut.push({ name: offer.name, why: `${offer.path} is not on PATH` });
      continue;
    }
    const bin = NEEDS[offer.name];
    if (bin && !findBin(bin, search).onPath) {
      leftOut.push({ name: offer.name, why: `the ${bin} program is not on PATH` });
      continue;
    }
    blocks.push({ name: offer.name, text });
  }
  const data = dataBlock(cfg, search, leftOut);
  if (data) blocks.push(data);
  return { blocks, leftOut };
}

function run(cfg, check) {
  const path = join(cfg, "rules", "hov-stack-tools.md");
  let tools = [],
    leftOut = [];
  const result = (state, reason) => {
    const note =
      state !== "blocked" && leftOut.length
        ? `; left out: ${leftOut.map((l) => `${l.name} (${l.why})`).join(", ")}`
        : "";
    return {
      code: state === "ok" ? 0 : state === "blocked" ? 1 : 3,
      state,
      path,
      reason: reason + note,
      tools,
      leftOut,
    };
  };
  try {
    // Pass the same config dir to Claude and the detector's settings reads.
    process.env.CLAUDE_CONFIG_DIR = cfg;
    const w = wanted(detect(), cfg);
    leftOut = w.leftOut;
    tools = w.blocks.map((b) => b.name);
    const mentions = tools.length
      ? `mentions ${tools.join(", ")}`
      : "no installed tool needs instruction lines";
    const desired = w.blocks.length
      ? HEADER + "\n" + w.blocks.map((b) => b.text).join("\n") + "\n"
      : null;
    const rules = dirname(path),
      parent = stat(rules);
    if (parent && parent.isSymbolicLink()) {
      let real = null;
      try {
        real = statSync(rules);
      } catch {}
      if (!real || !real.isDirectory())
        return result(
          "blocked",
          "rules/ is a symlink to something that is not a directory, so nothing is written: fix or remove it, then run ./setup again",
        );
      const have = ruleLines(rules);
      const lacking = w.blocks.filter(
        (b) =>
          !b.text
            .split("\n")
            .map((l) => l.trim())
            .filter(Boolean)
            .every((l) => have.has(l)),
      );
      if (!lacking.length)
        return result(
          "ok",
          tools.length
            ? `rules/ is a symlink, and a rules file there has the lines for ${tools.join(", ")}`
            : mentions,
        );
      return result(
        "missing",
        `rules/ is a symlink, so ./setup writes nothing into it: add the lines in ${lacking
          .map((b) => join(SOURCES, `${b.name}.md`))
          .join(", ")} to a rules file there`,
      );
    }
    if (parent && !parent.isDirectory())
      return result(
        "blocked",
        "rules/ is not a directory, so nothing is written: move it aside and run ./setup again",
      );
    const existing = stat(path);
    if (existing && existing.isSymbolicLink())
      return result(
        "blocked",
        `${FILE} is a symlink, so it is left as it is: remove it and run ./setup again`,
      );
    if (existing && !existing.isFile())
      return result(
        "blocked",
        `${FILE} is not a regular file, so it is left as it is: move it aside and run ./setup again`,
      );
    const before = existing ? readFileSync(path, "utf8") : null;
    if (before !== null && !before.startsWith(HEADER))
      return result(
        "blocked",
        `${FILE} was not written by ./setup, so it is left as it is: move it aside and run ./setup again`,
      );
    if (before === desired)
      return result("ok", desired ? `${FILE} is current; ${mentions}` : mentions);
    if (check)
      return result(
        before === null ? "missing" : "stale",
        before === null
          ? `${FILE} is not written yet: run ./setup`
          : desired === null
            ? `${FILE} names tools that are no longer installed: run ./setup`
            : `${FILE} is out of date with the installed tools: run ./setup`,
      );
    if (desired === null) unlinkSync(path);
    else {
      mkdirSync(rules, { recursive: true });
      const tmp = join(rules, `.hov-stack-tools-${randomUUID()}.tmp`);
      try {
        writeFileSync(tmp, desired, {
          flag: "wx",
          mode: existing ? existing.mode & 0o777 : 0o644,
        });
        renameSync(tmp, path);
      } finally {
        try {
          unlinkSync(tmp);
        } catch (e) {
          if (e.code !== "ENOENT") throw e;
        }
      }
    }
    return result(
      "ok",
      desired === null ? `${FILE} removed; ${mentions}` : `${FILE} updated; ${mentions}`,
    );
  } catch (e) {
    return result("blocked", String(e.message).replace(/\s*\n\s*/g, " "));
  }
}
function main(argv) {
  let cfg = configDir(),
    check = false,
    json = false;
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--check") check = true;
    else if (a === "--json") json = true;
    else if (
      a === "--config-dir" &&
      argv[i + 1] &&
      !argv[i + 1].startsWith("--")
    )
      cfg = argv[++i];
    else {
      process.stderr.write(
        `hov-setup: invalid argument ${a}\nusage: node instructions.mjs [--config-dir DIR] [--check] [--json]\n`,
      );
      return 2;
    }
  }
  const r = run(cfg, check);
  process.stdout.write(
    (json ? JSON.stringify(r, null, 2) : `${r.state}: ${r.reason}`) + "\n",
  );
  return r.code;
}
try {
  if (
    process.argv[1] &&
    realpathSync(process.argv[1]) ===
      realpathSync(fileURLToPath(import.meta.url))
  )
    process.exitCode = main(process.argv.slice(2));
} catch (e) {
  process.stderr.write(`hov-setup: ${e.message}\n`);
  process.exitCode = 1;
}
