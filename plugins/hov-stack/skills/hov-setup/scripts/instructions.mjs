#!/usr/bin/env node
/*
  Reads detect()'s live offer states and ../instructions/<offer>.md in offers.json order.
  Writes only the setup-owned regular file <config-dir>/rules/hov-stack-tools.md,
  atomically; removes it when no installed offer contributes. User files and symlinks
  are left alone. A failed detection changes nothing.

  Usage: node instructions.mjs [--config-dir DIR] [--check] [--json]
  Config dir: $CLAUDE_CONFIG_DIR, else ~/.claude. --check never writes.
  Exit: 0 ok; 3 missing/stale in --check; 1 blocked/read/write failure; 2 bad usage.
*/
import {
  lstatSync,
  mkdirSync,
  readFileSync,
  realpathSync,
  renameSync,
  unlinkSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { randomUUID } from "node:crypto";
import { configDir } from "./autoupdate.mjs";
import { detect } from "./detect.mjs";

const HEADER =
  "<!-- Generated by hov-stack: ./setup, ./setup --update and /hov-setup regenerate this file. Edits are lost. Lines come from plugins/hov-stack/skills/hov-setup/instructions/<offer>.md. -->\n";
function stat(path) {
  try {
    return lstatSync(path);
  } catch (e) {
    if (e.code === "ENOENT") return null;
    throw e;
  }
}
function run(cfg, check) {
  const path = join(cfg, "rules", "hov-stack-tools.md");
  const result = (state, reason, tools = []) => ({
    code: state === "ok" ? 0 : state === "blocked" ? 1 : 3,
    state,
    path,
    reason,
    tools,
  });
  try {
    // Pass the same config dir to Claude and the detector's settings reads.
    process.env.CLAUDE_CONFIG_DIR = cfg;
    const report = detect();
    const tools = [],
      lines = [];
    for (const offer of report.plugins) {
      if (offer.state !== "installed") continue;
      const source = new URL(
        `../instructions/${offer.name}.md`,
        import.meta.url,
      );
      let text;
      try {
        text = readFileSync(source, "utf8").trim();
      } catch (e) {
        if (e.code === "ENOENT") continue;
        throw e;
      }
      if (text) {
        tools.push(offer.name);
        lines.push(text);
      }
    }
    const desired = lines.length
      ? HEADER + "\n" + lines.join("\n") + "\n"
      : null;
    const rules = dirname(path),
      parent = stat(rules);
    if (parent && (parent.isSymbolicLink() || !parent.isDirectory()))
      return result(
        "blocked",
        "rules/ is a symlink or not a directory; nothing written",
        tools,
      );
    const existing = stat(path);
    if (existing && (existing.isSymbolicLink() || !existing.isFile()))
      return result(
        "blocked",
        "rules file is a symlink or not a regular file; nothing written",
        tools,
      );
    const before = existing ? readFileSync(path, "utf8") : null;
    if (before !== null && !before.startsWith(HEADER))
      return result(
        "blocked",
        "file was not generated by setup; left untouched",
        tools,
      );
    if (before === desired)
      return result(
        "ok",
        tools.length
          ? `unchanged; mentions ${tools.join(", ")}`
          : "no installed tools contribute lines",
        tools,
      );
    if (check)
      return result(
        before === null ? "missing" : "stale",
        "run ./setup to refresh installed tool instructions",
        tools,
      );
    if (desired === null) unlinkSync(path);
    else {
      mkdirSync(rules, { recursive: true });
      const tmp = join(rules, `.hov-stack-tools-${randomUUID()}.tmp`);
      try {
        writeFileSync(tmp, desired, {
          flag: "wx",
          mode: existing ? existing.mode & 0o777 : 0o644,
        });
        renameSync(tmp, path);
      } finally {
        try {
          unlinkSync(tmp);
        } catch (e) {
          if (e.code !== "ENOENT") throw e;
        }
      }
    }
    return result(
      "ok",
      desired === null
        ? "removed; no installed tools contribute lines"
        : `updated; mentions ${tools.join(", ")}`,
      tools,
    );
  } catch (e) {
    return result("blocked", e.message);
  }
}
function main(argv) {
  let cfg = configDir(),
    check = false,
    json = false;
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--check") check = true;
    else if (a === "--json") json = true;
    else if (
      a === "--config-dir" &&
      argv[i + 1] &&
      !argv[i + 1].startsWith("--")
    )
      cfg = argv[++i];
    else {
      process.stderr.write(
        `hov-setup: invalid argument ${a}\nusage: node instructions.mjs [--config-dir DIR] [--check] [--json]\n`,
      );
      return 2;
    }
  }
  const r = run(cfg, check);
  process.stdout.write(
    (json ? JSON.stringify(r, null, 2) : `${r.path}: ${r.state}: ${r.reason}`) +
      "\n",
  );
  return r.code;
}
try {
  if (
    process.argv[1] &&
    realpathSync(process.argv[1]) ===
      realpathSync(fileURLToPath(import.meta.url))
  )
    process.exitCode = main(process.argv.slice(2));
} catch (e) {
  process.stderr.write(`hov-setup: ${e.message}\n`);
  process.exitCode = 1;
}
